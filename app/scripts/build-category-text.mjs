// Rebuilds the category text coordinates of ucs/text_embeddings.npz with the q8 text model the
// app runs, because the audio coordinates they are compared with are q8. Same text, same means.
const ucs = path.resolve('../_experiments/cls_test/ucs');
const target = 'src/core/classify/ucs-data.generated.ts';
const modelFiles = path.resolve('../_experiments/e4_browser/models/Xenova/clap-htsat-unfused');
const executablePath = process.env.CHROMIUM_PATH ?? path.resolve('../_experiments/e4_browser/browsers/chromium-1194/chrome-mac/Chromium.app/Contents/MacOS/Chromium');

function checkMemory() {
  const output = execFileSync('memory_pressure', [], { encoding: 'utf8' });
  const free = Number(output.match(/System-wide memory free percentage:\s*(\d+)%/)?.[1]);
  assert(Number.isFinite(free) && free >= 30, `Memory free ${free}%; stopped before inference.`);
  return free;
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char !== '"') field += char;
      else if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
    } else if (char === '"') quoted = true;
    else if (char === ',') { row.push(field); field = ''; }
    else if (char === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = ''; }
    else field += char;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((values) => Object.fromEntries(header.map((name, index) => [name, values[index]])));
}

console.log(`MEMORY_FREE ${checkMemory()}%`);
const protocolBytes = await readFile(path.join(ucs, 'protocol.json'));
const csvBytes = await readFile(path.join(ucs, 'ucs.csv'));
const protocol = JSON.parse(protocolBytes.toString('utf8'));
const rows = parseCsv(csvBytes.toString('utf8').replace(/^\ufeff/, ''));
const { scale } = JSON.parse(await readFile(path.join(ucs, 'run_metadata.json'), 'utf8'));
assert.equal(rows.length, 753);
assert.equal(protocol.prompts.length, 753);
assert.equal(new Set(rows.map((row) => row.CatID.toLowerCase())).size, 753);
assert.equal(protocol.categories.length, 82);
assert.equal(protocol.restricted.length, 18);

const server = await createServer({ server: { port: 0, host: '127.0.0.1' } });
let browser;
let vectors;
try {
  await server.listen();
  browser = await chromium.launch({ executablePath, headless: true });
  const context = await browser.newContext();
  const page = await context.newPage();
  await context.route('https://huggingface.co/**', async (route) => {
    const name = route.request().url().split('/resolve/c28f2883575e590e04d3146ff0713c2448d691ba/')[1];
    try {
      const body = await readFile(path.join(modelFiles, name));
      await route.fulfill({ body, headers: { 'Access-Control-Allow-Origin': '*', 'Cross-Origin-Resource-Policy': 'cross-origin' } });
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      await route.continue();
    }
  });
  await page.goto(`${server.resolvedUrls.local[0]}src/model/verify.html`);
  await page.evaluate(async () => { window.model = await import('/src/model/index.ts'); });
  vectors = [];
  for (let start = 0; start < protocol.prompts.length; start += 32) {
    checkMemory();
    vectors.push(...await page.evaluate(async (sentences) =>
      (await window.model.embedText(sentences)).map((vector) => Array.from(vector)),
    protocol.prompts.slice(start, start + 32)));
    console.log(`PROMPTS ${vectors.length}/753`);
  }
} finally {
  await browser?.close();
  await server.close();
}

const categoryVectors = new Float32Array(82 * 512);
protocol.categories.forEach((category, index) => {
  const members = vectors.filter((_, row) => rows[row].Category === category);
  assert(members.length > 0, category);
  const mean = Array.from({ length: 512 }, (_, i) => members.reduce((sum, vector) => sum + vector[i], 0) / members.length);
  const norm = Math.hypot(...mean);
  categoryVectors.set(mean.map((value) => value / norm), index * 512);
});
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const base64 = Buffer.from(categoryVectors.buffer).toString('base64');
const catIds = Object.fromEntries(rows.map((row) => [row.CatID, row.Category]));
await writeFile(target, `// Generated by scripts/build-category-text.mjs. Do not edit.
// protocol.json sha256 ${hash(protocolBytes)}
// ucs.csv sha256 ${hash(csvBytes)}
export const CATEGORY_SCALE = ${scale};
export const DEFAULT_CATEGORIES = ${JSON.stringify(protocol.restricted)} as const;
export const CATEGORIES: readonly string[] = ${JSON.stringify(protocol.categories)};
export const CAT_IDS: Readonly<Record<string, string>> = ${JSON.stringify(catIds)};
/** Little-endian Float32 values, 512 per entry of CATEGORIES, q8 text model. */
export const CATEGORY_TEXT_BASE64 = '${base64}';
`);
console.log(`WROTE ${target} categories=82 prompts=${vectors.length}`);
